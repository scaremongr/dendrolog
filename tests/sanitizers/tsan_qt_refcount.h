// ============================================================================
// tsan_qt_refcount.h — показывает ThreadSanitizer счётчик ссылок контейнеров Qt.
//
// Подключается принудительно (-include) во все единицы трансляции ТОЛЬКО при
// -DDENDROLOG_SANITIZER=thread (см. корневой CMakeLists.txt); в обычную сборку
// не попадает.
//
// Зачем. Неявно разделяемые контейнеры (QList, QString, QHash, …) решают,
// писать на месте или отсоединяться, по счётчику ссылок:
//
//     воркер:     читает свою копию списка … отпускает её   (deref, 2 → 1)
//     GUI-поток:  needsDetach() видит 1 → пишет в тот же буфер на месте
//
// Запись идёт строго после чтения, и порядок держит сам счётчик: единицу
// GUI-поток может увидеть только после deref воркера. Но Qt читает счётчик
// через loadRelaxed(), а relaxed-чтение атомика TSan синхронизацией не считает
// (в отличие от deref — это fetch_sub с acq_rel, он «отдаёт»). Ребра
// happens-before нет, и TSan сообщает о гонке «запись GUI-потока / чтение
// воркера» всякий раз, когда между ними не случилось другой передачи: воркер
// закончил и отпустил снапшот, а GUI-поток дописал в список раньше, чем
// получил хоть одно событие. Так живут все снапшоты резидентного хранилища
// (LogScanSnapshot — копия вектора записей), и срабатывание зависит только от
// планировщика.
//
// Обёртки линкера (tsan_qt_sync.cpp) тут бессильны: проверка счётчика —
// inline-код заголовков Qt, вызова в библиотеку нет. Qt, собранный с TSan,
// тоже не помог бы: порядок чтения — свойство заголовка.
//
// Как. Для сборки под TSan чтение счётчика объявлено acquire-чтением: явная
// специализация QAtomicOps<int>::loadRelaxed. Машинный код на x86 и ARM тот
// же, поведение программы не меняется; меняется только то, что TSan узнаёт о
// порядке, — и узнаёт правду: значение счётчика действительно получено от
// потока, который сделал deref.
//
// Цена. Acquire-чтением становится КАЖДЫЙ loadRelaxed() у QAtomicInt /
// QBasicAtomicInt в нашем коде, не только счётчики ссылок. Гонку, в которой
// единственная «синхронизация» — пара «ref()/deref()/storeRelease() в одном
// потоке → loadRelaxed() в другом» на таком атомике, TSan пропустит. Свои
// флаги и счётчики проект держит в std::atomic, их это не касается.
//
// Проверка — tests/tsan_canary: режим cow (запись на месте после отпущенной
// копии — без отчётов) и cow-race (чтение буфера без удержания копии — отчёт
// обязателен). Привязано к устройству qatomic_cxx11.h из Qt 6.8: если шаблон
// переименуют, сборка под TSan не скомпилируется, если перестанут звать —
// упадёт режим cow.
// ============================================================================
#ifndef DENDROLOG_TSAN_QT_REFCOUNT_H
#define DENDROLOG_TSAN_QT_REFCOUNT_H

#ifdef __cplusplus

#include <QtCore/qbasicatomic.h>

template <>
template <>
inline int QAtomicOps<int>::loadRelaxed<int>(const std::atomic<int>& value) noexcept
{
    return value.load(std::memory_order_acquire);
}

#endif // __cplusplus

#endif // DENDROLOG_TSAN_QT_REFCOUNT_H
