#ifndef SCHEMACONVERTER_H
#define SCHEMACONVERTER_H

#include <QString>
#include <QStringList>

// ============================================================================
// SchemaConverter — перевод прежних форм схемы в шаблон строки
// (linetemplate.h). F-17, раздел 2, «Перевод старого»; с шага 9 блочной
// модели (LogPattern) в программе нет, и это ЕДИНСТВЕННОЕ место, которое
// знает прежний формат схемы — файл версии 3 («dynamic-block-schema»: блоки
// с обёртками и разделителями) и ещё более старую строку-паттерн
// («%d [%t] %p - %m»). Им пользуются:
//   • перевод каталога при запуске (SchemaStore::migrateToTemplates: файл
//     версии 3 → версия 4, оригинал — в converted-from-v3/);
//   • сохранённые состояния (documentstate: память файла, сессии,
//     last-session.json; схема по умолчанию в ini) — upgradeDefinition при
//     чтении, вкладка получает те же поля;
//   • отпечатки встроенных схем прежних выпусков (BuiltinSchemas: нетронутая
//     копия версии 3 узнаётся и обновляется шаблоном) — canonicalBlocks;
//   • импорт Grok в редакторе (fromGrok: та же таблица соответствий, что у
//     прежнего импорта, затем перевод блоков).
//
// Соответствие блоков шаблону:
//   • обёртки и литеральные разделители — литералами; пробельные — пробелом
//     шаблона; «авто»-промежуток между блоками (в прежнем движке [ \t]*) —
//     «{? ?}» (необязательные пробелы), рядом с пробелом шаблона — пробел;
//   • разделитель после самоограниченного блока (метка, уровень, число,
//     hex, IP, константа, блок с закрывающей обёрткой) необязателен —
//     «{?…?}», как «(?:…)?» прежнего генератора;
//   • регекс-разделитель из простых атомов (буквы, «\»-экранированные знаки,
//     [ \t], \s и пробел с ?, * и +) — литералами, пробелами и «{?…?}»;
//     иначе — безымянное поле «{_:/…/}» с тем же регексом;
//   • виды блоков — видами полей (Timestamp → time, Level → level, Integer →
//     int, HexText → hex, IpAddress → ip, FilePath → path, CustomRegex →
//     /регекс/, Text → text, Greedy text → greedy, Remainder и последний
//     Text без разделителя → rest); «ignored» — поле без имени; константа —
//     литералом, именованная — полем of(константа);
//   • Text, чей конец в новом движке не определён (следом пробел и поле без
//     формы), — word (заметка в notes).
// Имена колонок сохраняются буква в букву: на них стоят правила фильтров.
// Ключевая часть прежних схем («keyed», F-4) отбрасывается: JSON и logfmt —
// формат строк файла (F-17, шаг 7); переводятся её запасные блоки.
//
// Поведение на отклоняющихся строках может отличаться от прежнего каскада
// (нет поиска якоря с пропуском мусора и re-sync) — по слову автора это
// допустимо; на корпусе встроенных форматов поля те же (tests/line_template).
// ============================================================================

namespace SchemaConverter {

struct Result {
    bool ok = false;
    QString templateText;   ///< компилируется (LineTemplate), если ok
    QString error;          ///< почему не переведена, если !ok
    QStringList notes;      ///< что изменилось по смыслу (для отчёта о переводе)
};

/// Определение прежней формы: JSON версии ≤ 3 с массивом «blocks» или
/// строка-паттерн с «%»-спецификаторами. Шаблон (версия 4) и колонки формата
/// строк — нет.
bool isBlockDefinition(const QString& definition);

/// Блочная схема (JSON версии ≤ 3 или строка-паттерн) → шаблон по таблице
/// соответствий (сам перевод; тест сверяет его с ручными шаблонами).
Result fromBlocks(const QString& definition);

/// То, чем программа заменяет блочную схему (каталог, сохранённые состояния,
/// ini — одно правило, чтобы определения совпадали): встроенная схема
/// прежнего выпуска — ровно поставляемым шаблоном, иначе fromBlocks.
Result translate(const QString& definition);

/// Определение для программы: блочное — переведённым определением шаблона
/// (LineTemplateSchema::definition; встроенная схема прежнего выпуска —
/// ровно поставляемым шаблоном), ключевое прежних версий — пустое («без
/// схемы»), всё прочее и непереводимое (битое) — как есть (полей у такого
/// нет, но сохранённое не теряется). converted (может быть nullptr) — было
/// блочным.
QString upgradeDefinition(const QString& definition, bool* converted = nullptr);

/// Каноническая сериализация блочной схемы — буква в букву как у прежнего
/// LogPattern::serializeDefinition (отпечатки манифеста встроенных схем).
/// strict — с прежней проверкой (имена полей, регексы, Remainder последним).
bool canonicalBlocks(const QString& definition, QString* canonical, bool strict = false);

/// Определение ключевой схемы прежних версий (ключ «keyed», F-4): с F-17,
/// шаг 7 JSON и logfmt — формат строк файла. Сохранённое состояние и
/// умолчание с такой схемой читаются как «без схемы» (FieldSchemaController).
bool isRetiredKeyedDefinition(const QString& definition);

/// Grok-выражение → шаблон (та же таблица соответствий имён Grok, что у
/// прежнего импорта). Нет ни одного «%{…}» — !ok. Неизвестные имена — text,
/// перечислены в notes.
Result fromGrok(const QString& grokExpression);

} // namespace SchemaConverter

#endif // SCHEMACONVERTER_H
