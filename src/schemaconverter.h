#ifndef SCHEMACONVERTER_H
#define SCHEMACONVERTER_H

#include <QString>
#include <QStringList>

struct PatternDefinition;

// ============================================================================
// SchemaConverter — перевод прежней блочной схемы (PatternDefinition,
// logpattern.h) в шаблон строки (linetemplate.h). F-17, раздел 2, «Перевод
// старого»: каталог версии 3 переводится при первом запуске (шаг 9),
// определения в сохранённых состояниях — при чтении тем же конвертером.
//
// Соответствие:
//   • обёртки и литеральные разделители — литералами; пробельные — пробелом
//     шаблона; «авто»-промежуток между блоками (в прежнем движке [ \t]*) —
//     «{? ?}» (необязательные пробелы), рядом с пробелом шаблона — пробел;
//   • разделитель после самоограниченного блока (метка, уровень, число,
//     hex, IP, константа, блок с закрывающей обёрткой) необязателен —
//     «{?…?}», как «(?:…)?» прежнего генератора;
//   • регекс-разделитель из простых атомов (буквы, «\»-экранированные знаки,
//     [ \t], \s и пробел с ?, * и +) — литералами, пробелами и «{?…?}»;
//     иначе — безымянное поле «{_:/…/}» с тем же регексом;
//   • виды блоков — видами полей (Timestamp → time, Level → level, Integer →
//     int, HexText → hex, IpAddress → ip, FilePath → path, CustomRegex →
//     /регекс/, Text → text, Greedy text → greedy, Remainder и последний
//     Text без разделителя → rest); «ignored» — поле без имени; константа —
//     литералом, именованная — полем of(константа);
//   • Text, чей конец в новом движке не определён (следом пробел и поле без
//     формы), — word (заметка в notes).
// Имена колонок сохраняются буква в букву: на них стоят правила фильтров.
// Ключевая схема (JSON / logfmt) шаблоном не является — отказ (шаг 7: это
// формат строк файла).
//
// Поведение на отклоняющихся строках может отличаться от прежнего каскада
// (нет поиска якоря с пропуском мусора и re-sync) — по слову автора это
// допустимо; на корпусе встроенных форматов поля те же (tests/line_template).
// ============================================================================

namespace SchemaConverter {

struct Result {
    bool ok = false;
    QString templateText;   ///< компилируется (LineTemplate), если ok
    QString error;          ///< почему не переведена, если !ok
    QStringList notes;      ///< что изменилось по смыслу (для отчёта о переводе)
};

Result fromBlocks(const PatternDefinition& definition);

} // namespace SchemaConverter

#endif // SCHEMACONVERTER_H
