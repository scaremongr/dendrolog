#ifndef TIMEGAPS_H
#define TIMEGAPS_H

#include <QVector>
#include <QtGlobal>

// ============================================================================
// Паузы в логе без порядка строк (S-23): крупнейшие промежутки между
// СОСЕДНИМИ ПО ВРЕМЕНИ метками, в каком бы порядке их ни подавали.
//
// Зачем: одно-файловая индексная вкладка идёт в порядке файла, и пауза по
// соседним строкам у файла с метками не по порядку была ложной (10:00,
// 09:00, 10:05 → «65 мин» вместо 5) — тот же файл ниже и выше порога давал
// разные аномалии Gap.
//
// Как: шкала [tMin, tMax] — настоящие минимум и максимум меток
// (LogScanSnapshot::timeRange), kBins корзин, у каждой — минимум и максимум
// попавших меток (16 КБ на расчёт, O(1) на метку, без сортировки и без
// материализации меток). Промежуток между соседними по времени метками
// разных корзин — «максимум непустой корзины → минимум следующей непустой» —
// точен; внутри корзины промежуток не длиннее exactAboveMs(). Поэтому всё,
// что длиннее exactAboveMs(), найдено ТОЧНО (те же числа, что у прохода по
// отсортированным меткам), короче — не ищется вовсе.
//
// Порядок при равной длине — раньше по времени первым (как у прохода по
// отсортированной вкладке со строгим «больше»).
// ============================================================================

class TimeGaps {
public:
    struct Gap {
        qint64 ms = 0;     // длина: toMs − fromMs
        qint64 fromMs = 0; // последняя метка перед паузой
        qint64 toMs = 0;   // первая метка после неё
        bool operator==(const Gap& o) const
        {
            return ms == o.ms && fromMs == o.fromMs && toMs == o.toMs;
        }
    };

    static constexpr int kBins = 1024;

    // Шкала — настоящие минимум и максимум меток (tMin ≤ tMax, в пределах
    // TimeBins: годы 0001–9999, разность × kBins не переполняет qint64).
    TimeGaps(qint64 tMinMs, qint64 tMaxMs);

    // Метка вне шкалы — в крайнюю корзину со своим значением (страховка:
    // снимок индекса бывает на порцию впереди или позади строк).
    void add(qint64 ms);

    // Промежуток длиннее этого найден точно.
    qint64 exactAboveMs() const { return m_span / kBins; }

    // До count крупнейших промежутков длиной не меньше minMs: по убыванию
    // длины, при равной — раньше по времени. Точно при minMs > exactAboveMs().
    QVector<Gap> largest(int count, qint64 minMs) const;

private:
    qint64 m_tMin = 0;
    qint64 m_span = 1; // tMax − tMin + 1: tMax — в последней корзине
    QVector<qint64> m_lo, m_hi; // пустая корзина: lo > hi
};

#endif // TIMEGAPS_H
