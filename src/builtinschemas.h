#ifndef BUILTINSCHEMAS_H
#define BUILTINSCHEMAS_H

#include <QList>
#include <QPair>
#include <QString>
#include <QStringList>

// ---------------------------------------------------------------------------
// BuiltinSchemas — установка встроенных схем полей в каталог схем.
//
// Встроенные схемы — обычные файлы *.json (resources/patterns/, в exe — как
// ресурсы :/patterns). Установка копирует их в каталог схем пользователя
// (<configDir>/patterns), откуда их читает SchemaStore, как любые другие.
// Каталог-источник и каталог назначения — параметры: тест гоняет установку во
// временных каталогах.
//
// Что уже сделано, помнит манифест — файл kManifestFileName в каталоге
// назначения (не *.json, поэтому SchemaStore его схемой не считает). На
// встроенную схему (по имени файла) он хранит состояние:
//   installed + отпечаток — схема установлена такой (имя + каноническая
//                           схема, форматирование файла не важно);
//   declined              — схему не ставили: на её месте уже было своё.
//
// Правила одного прогона, для каждой встроенной схемы:
//   • в манифесте её нет (первая установка или схема новая в этой версии):
//       – файла с таким именем нет и ни у одной схемы каталога нет такого же
//         отображаемого имени — файл копируется, installed;
//       – файл с таким именем есть и совпадает со встроенной — installed без
//         записи (принимается как уже установленный);
//       – файл с таким именем есть, но другой, или то же отображаемое имя у
//         чужого файла — declined, файл пользователя не трогается никогда;
//   • installed, файла нет — пользователь её удалил (или переименовал сам
//     файл): не воскрешается;
//   • installed, файл совпадает с отпечатком, а встроенная схема изменилась
//     (исправлена в новой версии) — файл перезаписывается новой, отпечаток
//     обновляется;
//   • installed, файл не совпадает с отпечатком — пользователь её изменил:
//     не трогается. Редактор схем пишет правку и переименование в тот же файл
//     (SchemaStore::sync), так что это — «изменена», а не «удалена». Описание
//     и прочие метаданные в отпечаток не входят: правка только описания или
//     пересохранение без правок схему изменённой не делают, и исправленная
//     версия заменит её вместе с описанием;
//   • declined — не трогается.
// Снятые с поставки (kRetired: «JSON Lines» и «logfmt» — с F-17, шаг 7 это
// формат строк файла, а не схема):
//   • installed, файл нетронут (имя, ключевая часть и запасной блок — как
//     поставлялись) — файл удаляется, retired;
//   • installed, файла нет — retired; изменён пользователем или declined —
//     не трогается (читается своим запасным блоком «Message» — не сломан);
//   • retired — больше не воскрешается (в поставке его и нет).
// Если манифест потерян, удалённые встроенные схемы вернутся при следующем
// запуске, изменённые пользователем — останутся declined: потеря манифеста
// никогда не перезаписывает пользовательский файл.
// ---------------------------------------------------------------------------
namespace BuiltinSchemas {

inline constexpr const char* kManifestFileName = ".builtin-schemas";

struct InstallReport {
    QStringList installed;   ///< Имена файлов, скопированных впервые.
    QStringList updated;     ///< Перезаписаны исправленной встроенной версией.
    QStringList declined;    ///< Впервые отклонены: на их месте было своё.
    QStringList retired;     ///< Снятые с поставки нетронутые копии удалены.
    QStringList errors;      ///< Ошибки чтения/записи, по строке на ошибку.
    /// Для обновлённых: (прежняя каноническая схема, новая) — чтобы выбранная
    /// пользователем схема не «потерялась» после обновления.
    QList<QPair<QString, QString>> replaced;

    bool changed() const
    {
        return !installed.isEmpty() || !updated.isEmpty() || !retired.isEmpty();
    }
};

/// Ставит встроенные схемы из \a sourceDir (каталог или ресурс ":/patterns")
/// в \a targetDir по правилам выше. Каталог назначения создаётся при нужде.
InstallReport install(const QString& sourceDir, const QString& targetDir);

/// Разбирает файл схемы: отображаемое имя (ключ "name", иначе \a fallbackName)
/// и каноническая сериализация. strict — с проверкой LogPattern::
/// validateDefinition (так проверяются встроенные схемы).
bool parseSchemaFile(const QByteArray& bytes, const QString& fallbackName,
                     QString* name, QString* canonical, bool strict = false);

} // namespace BuiltinSchemas

#endif // BUILTINSCHEMAS_H
