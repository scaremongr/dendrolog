#ifndef GOTOLOCATION_H
#define GOTOLOCATION_H

#include "logfile.h"

#include <QDate>
#include <QDateTime>
#include <QString>

class LogModel;

// ============================================================================
// GoToLocation — переход к строке файла или ко времени (Go to Line / Time,
// Ctrl+G) без виджетов: разбор ввода и поиск видимой строки. Диалог и
// MainWindow только показывают результат; покрыто tests/goto_location на
// обоих бэкендах.
//
// Ввод — одно поле:
//   • только цифры (пробелы-разделители разрядов допускаются) — номер строки
//     ФАЙЛА с 1, тот же, что показывает Entry Details. 0 — первая строка;
//   • всё остальное — время: `HH:mm[:ss[.fff]]`, дата `yyyy-MM-dd`, либо оба
//     через пробел или `T`; необязательная зона (`Z`, `±hh[:mm]`, `UTC`).
//     Время без даты берёт дату опорного момента (referenceTime) — в той же
//     зоне, в которой набрано время. Момент считает
//     LineClassifier — политика времени (локальное без зоны, усечение дроби)
//     та же, что при разборе лога.
//
// Куда попадаем:
//   • строка: если она скрыта фильтром — следующая видимая за её местом в
//     порядке вкладки, иначе последняя; номер за концом файла — последняя
//     строка файла (LogStore::nearestVisibleRowForLine);
//   • время: первая видимая строка не раньше него; позже последней метки —
//     последняя строка с меткой.
// exact == false — попали не ровно туда, куда просили; UI говорит об этом.
//
// Вкладка с несколькими файлами: номер строки относится к ОДНОМУ файлу, его
// выбирает вызывающий (файл текущей строки, в диалоге — список файлов).
// file == nullptr — файл первой видимой строки.
//
// Ловушка: на одно-файловой индексной вкладке строки идут в порядке файла, и
// переход ко времени — двоичный поиск по меткам (firstVisibleRowAtOrAfter),
// как у клика по таймлайну: на файле с метками не по порядку он приблизителен.
// ============================================================================

struct GoToTarget {
    enum class Kind { Invalid, Line, Time };
    Kind kind = Kind::Invalid;
    qint64 line = 0;   // с 1
    QDateTime time;
};

struct GoToResult {
    int row = -1;        // видимая строка; -1 — перейти некуда
    bool exact = false;  // строка с запрошенным номером / ровно это время
    LogFilePtr file;     // файл найденной строки
    qint64 line = 0;     // её номер в этом файле
    QDateTime time;      // её метка (может быть невалидной)
};

namespace GoToLocation {

GoToTarget parse(const QString& input, const QDateTime& reference);

// Опорный момент для времени без даты: метка текущей строки, иначе начало
// лога. Невалиден, если в документе нет ни одной метки.
QDateTime referenceTime(const LogModel& model, int currentRow);

GoToResult resolve(const LogModel& model, const GoToTarget& target, const LogFile* file);

} // namespace GoToLocation

#endif // GOTOLOCATION_H
