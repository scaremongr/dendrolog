#pragma once

#include <QString>
#include <QStringList>

// ============================================================================
// FileLabels — короткие метки файлов слитой вкладки (U-23, часть 2).
//
// Метка различает файлы, а не повторяет имя: колонка меток слева от текста
// одной ширины на вкладку, и длинное имя не должно её раздувать.
//
// Правило build(names, maxChars):
//   • все имена помещаются в maxChars — метки равны именам;
//   • иначе у всех имён убираются общий префикс и общий суффикс — целыми
//     кусками по границам «-», «_», «.», пробел — и на их месте ставится
//     «…»; у каждого имени остаётся хотя бы один кусок;
//   • остаток длиннее предела — выпускается середина («abc…xyz»);
//   • метки попарно различны: совпавшим (одинаковые имена из разных
//     каталогов, обрезка) дописывается «~2», «~3», … по порядку.
// Пример: payment-service-prod-eu-1.log и payment-service-prod-us-1.log при
// пределе 12 — «…eu…» и «…us…».
//
// Чистая функция, ядро (без виджетов); O(суммарной длины имён).
// ============================================================================

// Режим метки файла на строке слитой вкладки (View → File Labels, глобально).
enum class FileLabelMode {
    Name,       // колонка с меткой и полоса цвета файла (по умолчанию)
    ColorOnly,  // только полоса цвета; имена — в легенде
    Hidden,     // ни колонки, ни полосы, ни легенды
};

namespace FileLabels {

constexpr int kDefaultMaxChars = 16;
inline constexpr QChar kEllipsis{0x2026};

QStringList build(const QStringList& names, int maxChars = kDefaultMaxChars);

// Имя режима в ini ([View] fileLabels) и обратно; неизвестное — Name.
QString modeName(FileLabelMode mode);
FileLabelMode modeFromName(const QString& name);

} // namespace FileLabels
